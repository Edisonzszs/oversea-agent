// 查表：将 label/stem 归一化后匹配
export function lookupQA(label: string): QAEntry | null {
  const norm = (s: string) => s.replace(/[\s　（）()（）]/g, "").toLowerCase();
  const nl = norm(label);
  for (const item of LIB) {
    if (item.match.some(m => nl.includes(norm(m)) || norm(m).includes(nl.slice(0, Math.min(nl.length, 6))))) {
      return item.entry;
    }
  }
  return null;
}
